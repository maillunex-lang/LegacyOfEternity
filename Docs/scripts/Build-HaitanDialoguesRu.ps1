# Prefer QuestConfig kind when available; else keyword heuristics on original goalFormat.
function GoalFormatRu([string]$fmt, [int]$kind = 0) {
  switch ($kind) {
    1 { return 'Поговорите с: %s' }
    2 { return 'Убейте: %s' }
    4 { return 'Соберите: %s' }
  }
  if ([string]::IsNullOrWhiteSpace($fmt)) { return 'Цель: %s' }
  if ($fmt -match 'Собеседник|與.*對話|对话') { return 'Поговорите с: %s' }
  if ($fmt -match 'Уничтож|Убейте|剿滅|擊殺') { return 'Убейте: %s' }
  if ($fmt -match 'Соберите|採集|Выберите') { return 'Соберите: %s' }
  return 'Цель: %s'
}

