# Parse original quest docs for goalFormat fallback
$origGoalFmt = @{}
Get-Content $docQuestPath | ForEach-Object {
  if ($_ -match '\[(10017\d{2})\]=\{(10017\d{2}),\s*"(.*?)",\s*"(.*?)",\s*"(.*?)",\s*"(.*?)",\s*"(.*?)",\s*"(.*?)"\}') {
    $origGoalFmt[[int]$Matches[1]] = $Matches[6]
  }
}

# Quest → acceptStoryId from t_quest
$questStory = @{}
Get-Content $questPath | ForEach-Object {
  if ($_ -match '\[(10017\d{2})\]=\{(.+)\}') {
    $qid = [int]$Matches[1]
    $story = 0
    foreach ($tok in ($Matches[2] -split ',')) {
      $t = $tok.Trim().Trim('"')
      if ($t -match '^101\d{3}$') { $story = [int]$t; break }
    }
    $questStory[$qid] = $story
  }
}

# Dialogue meta for npcId per story
$storyNpc = @{}
Get-Content $dialPath | ForEach-Object {
  if ($_ -match '\[(\d+)\]=\{(\d+),\s*(\d+),\s*(\d+),') {
    $group = [int]$Matches[3]
    $npcId = [long]$Matches[4]
    if (-not $storyNpc.ContainsKey($group) -and $npcId -gt 0) {
      $storyNpc[$group] = $npcId
    }
  }
}

# QuestConfig kinds from exported HaitanQuests.json
$kindById = @{}
if (Test-Path $questsJsonPath) {
  $hqKinds = Get-Content $questsJsonPath -Raw -Encoding UTF8 | ConvertFrom-Json
  foreach ($qq in $hqKinds.quests) { $kindById[[int]$qq.id] = [int]$qq.kind }
}

$quests = @()
foreach ($qid in (1001701..1001799)) {
  if (-not $questRu.ContainsKey($qid)) { continue }
  $ru = $questRu[$qid]
  $fmtSrc = if ($origGoalFmt.ContainsKey($qid)) { $origGoalFmt[$qid] } else { '' }
  $sid = if ($questStory.ContainsKey($qid)) { [int]$questStory[$qid] } else { 0 }
  $kind = if ($kindById.ContainsKey($qid)) { [int]$kindById[$qid] } else { 0 }
  $quests += [ordered]@{
    id = $qid
    name = $ru[0]
    summary = $ru[1]
    goalFormat = (GoalFormatRu $fmtSrc $kind)
    goalTarget = $ru[2]
    acceptStoryId = $sid
  }
}

$stories = @()
foreach ($sid in ($storyRu.Keys | Sort-Object)) {
  $npc = if ($storyNpc.ContainsKey($sid)) { [long]$storyNpc[$sid] } else { 0L }
  $stories += [ordered]@{
    storyId = [int]$sid
    npcId = $npc
    lines = @($storyRu[$sid])
  }
}

$greetings = @()
foreach ($npcId in ($greetRu.Keys | Sort-Object)) {
  $greetings += [ordered]@{
    dialogueId = [int]($npcId - 201000000)
    npcId = [long]$npcId
    text = $greetRu[$npcId]
  }
}

$payload = [ordered]@{
  source = 't_doc_quest + t_quest + t_doc_dialogue (Darklord) → RU translation'
  language = 'ru'
  mapId = 110200011
  quests = $quests
  stories = $stories
  npcGreetings = $greetings
}

$json = $payload | ConvertTo-Json -Depth 8
